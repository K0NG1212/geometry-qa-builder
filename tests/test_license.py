"""W2: the licence audit must cover every source and must not go quiet about an open question.

What these pin: every admitted question and every published card belongs to a source the audit names; no
source whose terms forbid redistribution has its coordinates published; a share-alike source cannot lose its
open decision by someone re-running the export; every source whose coordinates we publish has its licence
confirmed by the source itself, quoted with the date its page was read; the licence recorded for each
instance now exists and no longer calls SAMPL9 structures MIT; and the cards whose prose runs word for word
with the paper are listed rather than averaged away.

The published bank still carries the old licence strings -- they are generated by a run, and the run is
re-made on 11/05-11/08 -- so the stale instances are listed here by name. When the re-run lands, the list
goes red and is deleted.
"""
import json
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / 'tools'))
import export_license_audit as audit  # noqa: E402

AUDIT = json.loads((ROOT / 'docs/data/license-audit.json').read_text(encoding='utf-8'))
CATALOG = json.loads((ROOT / 'docs/data/catalog.json').read_text(encoding='utf-8'))
WORKBENCH = json.loads((ROOT / 'docs/data/family-workbench.json').read_text(encoding='utf-8'))
MANIFEST = {s['id']: s for s in json.loads((ROOT / 'templates/family-manifest.json').read_text(encoding='utf-8'))['items']}
ADMITTED = [q for q in CATALOG['questions'] if q.get('lifecycle') == 'active' and q.get('familyInstance')]
ROWS = {r['source']: r for r in AUDIT['rows']}


class CoverageTests(unittest.TestCase):
    def test_every_admitted_question_belongs_to_a_source_the_audit_names(self):
        self.assertEqual(sorted({q['paper'] for q in ADMITTED} - set(ROWS)), [])
        self.assertEqual(sum(r['questions'] for r in AUDIT['rows']), len(ADMITTED))
        self.assertEqual(AUDIT['questions'], len(ADMITTED))

    def test_every_published_card_belongs_to_a_source_the_audit_names(self):
        # A card is published bytes of its own; a new one must bring its paper's licence with it.
        papers = {card.get('paper') for _, card in audit.cards()}
        self.assertEqual(sorted(papers - set(ROWS)), [])
        self.assertEqual(len(AUDIT['quote_scan']), len(audit.cards()))

    def test_every_source_states_a_known_licence_or_says_it_relies_on_none(self):
        for row in AUDIT['rows']:
            if row['license'] is None:
                self.assertEqual(set(row['publishes']) - {'our_coordinates', 'our_text'}, set(), row['source'])
            else:
                self.assertIn(row['license'], audit.LICENCES, row['source'])
                self.assertTrue(row['evidence_paths'] or row['stated_by_source'], row['source'])
                for path in row['evidence_paths']:
                    self.assertTrue((ROOT / path).exists(), path)


class RedistributionTests(unittest.TestCase):
    def test_no_source_that_forbids_redistribution_has_its_coordinates_published(self):
        for row in AUDIT['rows']:
            if 'upstream_coordinates' in row['publishes'] and row['license']:
                self.assertTrue(audit.LICENCES[row['license']]['republish'],
                                '%s: %s 不允许转载' % (row['source'], row['license']))
        self.assertEqual([r['source'] for r in AUDIT['rows'] if r['verdict'] == 'blocked'], [])

    def test_a_share_alike_source_keeps_its_decision_open_until_it_is_recorded(self):
        # OE62 is CC BY-SA 4.0 and 5 questions publish its coordinates: whether the released dataset is
        # CC BY-SA, carries a CC BY-SA subset, or drops those five is the user's call, not the exporter's.
        share = [r for r in AUDIT['rows'] if r['license'] and audit.LICENCES[r['license']]['share_alike']]
        self.assertEqual([r['source'] for r in share], ['oe62'])
        for row in share:
            self.assertEqual(row['verdict'], 'decision_open')
            self.assertIn('licence-share-alike:' + row['source'], [f['id'] for f in AUDIT['findings']])

    def test_attribution_is_carried_for_every_source_that_requires_it(self):
        for row in AUDIT['rows']:
            if row['license'] and audit.LICENCES[row['license']]['attribution']:
                self.assertIn('署名', row['obligations'], row['source'])
                for question in (q for q in ADMITTED if q['paper'] == row['source']):
                    self.assertTrue(question.get('attribution'), question['id'])


class StatementTests(unittest.TestCase):
    """The licence pages read on 2026-11-02: the quote is the evidence, so it must not drift.

    Before this, eight databases and datasets had their coordinates published on a licence that only a record
    of ours stated. The statements file holds what each source's own page says, quoted, with the date. These
    tests keep the quote, the row that cites it, and the sources.json beside the assets saying one thing.
    """

    RECORD = json.loads((ROOT / audit.STATEMENTS_FILE).read_text(encoding='utf-8'))
    # The sources.json files that repeat a statement next to the assets it covers.
    BESIDE_ASSETS = sorted(p.relative_to(ROOT).as_posix() for p in ROOT.glob('docs/**/sources*.json')
                           if 'license_statement' in json.loads(p.read_text(encoding='utf-8')))

    def test_every_statement_says_which_page_and_when(self):
        for sid, entry in self.RECORD['statements'].items():
            self.assertIn(entry['license'], audit.LICENCES, sid)
            for field in ('covers', 'url', 'read_on', 'quote', 'obligation'):
                self.assertTrue(entry.get(field), '%s 缺 %s' % (sid, field))
            self.assertTrue(entry['url'].startswith('https://'), sid)
            self.assertRegex(entry['read_on'], r'^\d{4}-\d{2}-\d{2}$')

    def test_a_source_whose_page_was_read_is_marked_so_and_quotes_it(self):
        pages = audit.statements()
        self.assertEqual(sorted(pages), sorted(r['source'] for r in AUDIT['rows'] if r['confirmed_by_page']))
        for row in AUDIT['rows']:
            page = pages.get(row['source'])
            if page is None:
                self.assertIsNone(row['confirmed_by_page'], row['source'])
                self.assertNotEqual(row['confirmation'], 'publisher_page', row['source'])
                continue
            self.assertEqual(row['confirmed_by_page']['quote'], page['quote'], row['source'])
            self.assertEqual(row['license'], page['license'], row['source'])
            self.assertIn(audit.STATEMENTS_FILE, row['evidence_paths'], row['source'])
            # A local publisher copy still outranks a page, so only those two count as confirmed.
            self.assertIn(row['confirmation'], ('publisher_copy', 'publisher_page'), row['source'])

    def test_no_source_still_rests_on_a_record_of_ours_alone_for_republished_coordinates(self):
        # This is the finding the statements file was written to close; it must stay closed.
        left = [r['source'] for r in AUDIT['rows'] if 'upstream_coordinates' in r['publishes']
                and r['confirmation'] == 'repo_record_only']
        self.assertEqual(left, [], '这些来源的坐标已发布，而许可只有我们自己的记录')
        self.assertNotIn('licence-recorded-by-us-only', [f['id'] for f in AUDIT['findings']])

    def test_the_page_never_contradicts_the_licence_the_repo_declares(self):
        self.assertEqual([f['id'] for f in AUDIT['findings'] if f['id'].startswith('licence-page-mismatch')], [])
        for row in AUDIT['rows']:
            if row['confirmed_by_page'] and row['declared_in_repo']:
                self.assertEqual(row['license'], row['declared_in_repo'], row['source'])

    def test_the_record_beside_the_assets_repeats_the_statement_word_for_word(self):
        self.assertTrue(self.BESIDE_ASSETS)
        for rel in self.BESIDE_ASSETS:
            block = json.loads((ROOT / rel).read_text(encoding='utf-8'))['license_statement']
            entry = self.RECORD['statements'][block['statement']]
            self.assertEqual(block['record'], audit.STATEMENTS_FILE, rel)
            for field in ('license', 'url', 'read_on', 'quote', 'obligation'):
                self.assertEqual(block[field], entry[field], '%s 的 %s 与记录不一致' % (rel, field))

    def test_a_page_that_could_not_be_opened_is_listed_not_claimed(self):
        for miss in self.RECORD.get('not_reachable', []):
            self.assertTrue(miss['why'], miss['url'])
            self.assertIn(miss['url'], AUDIT['statements']['not_reachable'])
            self.assertIn('licence-page-unreachable', [f['id'] for f in AUDIT['findings']])
            # and no statement pretends to quote it
            self.assertNotIn(miss['url'], [e['url'] for e in self.RECORD['statements'].values()])


class RecordedLicenceTests(unittest.TestCase):
    # Instances whose published licence string is still the old one. The manifest is already right; these
    # become right when the bank is re-made.
    PENDING_RERUN_BLANK = {'FC-QNP007', 'FC-QNP008', 'FC-QNP009', 'FC-QNP010', 'FC-QNP011',
                           'FC-MNP006', 'FC-MNP007', 'FC-MNP010',
                           'FC-CNP007', 'FC-CNP008', 'FC-CNP009', 'FC-CNP011'}
    PENDING_RERUN_MIT = {'FA-ANG-BCD', 'FA-ANG-WP6', 'FA-ANG-DMBCD', 'FA-HG-EV1', 'FA-HG-EV2', 'FA-HG-EV3',
                         'FA-HG-DES1', 'FA-HG-DES2', 'FA-ROT-G9-101', 'FA-ROT-G2-110', 'FA-ISO-G9-110',
                         'FA-ISO-G13-111', 'FA-DIST-WP6-C20O22'}

    def test_the_manifest_records_a_licence_for_every_instance(self):
        self.assertEqual(sorted(i for i, s in MANIFEST.items() if not s.get('license')), [])

    def test_the_manifest_never_calls_a_structure_or_a_measurement_table_mit(self):
        # MIT covers the SAMPL9 repository's software; the host/guest structures and the ITC table are
        # "all other materials", which its README puts under CC BY 4.0.
        self.assertEqual(sorted(i for i, s in MANIFEST.items() if 'MIT' in s['license']), [])
        sampl9 = [q['familyInstance'] for q in ADMITTED if q['paper'] == 'sampl9']
        self.assertEqual(len(sampl9), 13)
        for instance in sampl9:
            self.assertIn('CC BY 4.0', MANIFEST[instance]['license'], instance)
            # The provenance line must not call the whole challenge MIT either: the README splits it.
            source = MANIFEST[instance].get('source') or ''
            self.assertNotIn('(MIT License)', source, instance)
            if 'MIT' in source:
                self.assertIn('CC BY 4.0', source, instance)

    def test_the_pending_lists_hold_nothing_the_latest_run_has_already_fixed(self):
        teachers = {t['id']: t for t in WORKBENCH['teacher_answers']}
        packets = {p['id'] for p in WORKBENCH['student_packets']}
        blank = {i for i, t in teachers.items() if not t.get('license') and i in packets}
        mit = {i for i, t in teachers.items() if 'MIT' in (t.get('license') or '') and i in packets}
        self.assertEqual(sorted(self.PENDING_RERUN_BLANK - blank), [], 'delete these from PENDING_RERUN_BLANK')
        self.assertEqual(sorted(self.PENDING_RERUN_MIT - mit), [], 'delete these from PENDING_RERUN_MIT')
        self.assertEqual(sorted(blank - self.PENDING_RERUN_BLANK), [])      # and no new one appeared
        self.assertEqual(sorted(mit - self.PENDING_RERUN_MIT), [])


class QuoteTests(unittest.TestCase):
    def test_a_card_whose_prose_runs_with_the_paper_is_listed_not_averaged(self):
        flagged = [r for r in AUDIT['quote_scan'] if r.get('needs_rewording')]
        self.assertTrue(flagged)                                  # the scan found some; they are the queue
        for row in flagged:
            self.assertGreaterEqual(row['longest_run'], AUDIT['quote_threshold'])
            self.assertIn(row['card'], ROWS[row['source']]['cards_to_reword'])
        self.assertIn('card-prose-verbatim', [f['id'] for f in AUDIT['findings']])

    def test_no_card_carries_a_whole_sentence_of_the_paper(self):
        # 20 words is no longer a shared clause; it would be a copied sentence, which no licence here allows
        # for the non-CC sources and which the cards' own method forbids for all of them.
        worst = max((r['longest_run'] for r in AUDIT['quote_scan'] if r['checked']), default=0)
        self.assertLess(worst, 20, 'rewrite the card before publishing it')

    def test_an_unchecked_card_is_recorded_as_unchecked(self):
        for row in AUDIT['quote_scan']:
            if not row['checked']:
                self.assertIn('why', row)
                self.assertNotIn('longest_run', row)              # never a number we did not measure


class WrittenUpTests(unittest.TestCase):
    """The two pages a reader sees must quote the audit's numbers, not numbers someone typed."""

    PAGES = ('LICENSING.md', 'MEETING_2026-11-04.md', 'PROJECT_STATUS.md')

    def test_the_headline_counts_appear_as_computed(self):
        totals = {}
        for row in AUDIT['rows']:
            for kind, n in row['publishes'].items():
                totals[kind] = totals.get(kind, 0) + n
        self.assertEqual(sum(totals.values()), len(ADMITTED))
        wanted = list(totals.values()) + [AUDIT['verdicts']['clear'], AUDIT['verdicts']['recheck'],
                                          AUDIT['sources']]
        for page in self.PAGES:
            text = (ROOT / page).read_text(encoding='utf-8')
            for number in wanted:
                self.assertIn(str(number), text, '%s 少了 %d' % (page, number))
        # The card count belongs to the page that lists the cards.
        self.assertIn(str(len(AUDIT['quote_scan'])), (ROOT / 'LICENSING.md').read_text(encoding='utf-8'))

    def test_the_tables_in_licensing_are_the_generated_ones(self):
        # Four tables (verdicts, the three publish kinds, the per-source rows, the quoted pages) live between
        # markers. Hand-editing a row there would have gone unnoticed before; now it fails here.
        text = (ROOT / 'LICENSING.md').read_text(encoding='utf-8')
        for name, build_table in audit.BLOCKS.items():
            begin, end = '<!-- %s:begin -->' % name, '<!-- %s:end -->' % name
            self.assertIn(begin, text, name)
            self.assertEqual(text.split(begin)[1].split(end)[0].strip(), build_table(AUDIT).strip(), name)

    def test_nothing_claims_a_source_is_blocked_or_clean_beyond_the_audit(self):
        licensing = (ROOT / 'LICENSING.md').read_text(encoding='utf-8')
        self.assertIn('不可发布 | **%d 个**' % AUDIT['verdicts']['blocked'], licensing)
        unchecked = sum(1 for r in AUDIT['quote_scan'] if not r['checked'])
        if unchecked:
            self.assertIn('%d 张未检' % unchecked, licensing)


class FreshnessTests(unittest.TestCase):
    def test_the_published_audit_is_what_the_tool_builds_today(self):
        absent = [s['fulltext'] for s in audit.SOURCES.values()
                  if s.get('fulltext') and not (ROOT / s['fulltext']).exists()]
        if absent:
            self.skipTest('%d 篇全文不在本机，重算会把已核对的结果降级为 unchecked' % len(absent))
        built = audit.build()
        for key in sorted(set(built) | set(AUDIT)):
            if key == 'date':
                continue
            self.assertEqual(built[key], AUDIT[key], 'docs/data/license-audit.json 过期：%s' % key)


